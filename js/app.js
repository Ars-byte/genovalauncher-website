const LangManager = (() => {
  const STORAGE_KEY = 'sunshine-lang'; let current = 'es';
  const t = (key) => (I18N[current] && I18N[current][key]) || (I18N['en'] && I18N['en'][key]) || key;
  const apply = (lang) => {
    current = lang; localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.setAttribute('lang', lang);
    document.querySelectorAll('[data-i18n]').forEach(el => { const v = t(el.dataset.i18n); if (v) el.innerHTML = v; });
    document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
  };
  const init = () => {
    apply(localStorage.getItem(STORAGE_KEY) || 'es');
    document.querySelectorAll('.lang-btn').forEach(b => b.addEventListener('click', () => apply(b.dataset.lang)));
  };
  return { init, t };
})();

const ThemeManager = (() => {
  const K = 'sunshine-theme';
  const apply = (t) => {
    document.documentElement.setAttribute('data-theme', t);
    document.querySelectorAll('.theme-toggle').forEach(b => {
      b.querySelector('.icon-sun').style.display = t === 'dark' ? 'inline' : 'none';
      b.querySelector('.icon-moon').style.display = t === 'light' ? 'inline' : 'none';
    });
  };
  const init = () => {
    apply(localStorage.getItem(K) || (window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light'));
    document.querySelectorAll('.theme-toggle').forEach(b => b.addEventListener('click', () => {
      const n = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
      localStorage.setItem(K, n); apply(n);
    }));
  };
  return { init };
})();

document.addEventListener('DOMContentLoaded', () => {
  ThemeManager.init(); LangManager.init();

  // Tab switcher
  document.querySelectorAll('[data-tabs]').forEach(group => {
    const key = group.dataset.tabs;
    group.querySelectorAll('.tab-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        group.querySelectorAll('.tab-btn').forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        document.querySelectorAll(`[data-tab-panel="${key}"]`).forEach(p => {
          p.style.display = p.dataset.tabId === btn.dataset.tab ? 'block' : 'none';
        });
      });
    });
  });

  // Copy buttons
  document.querySelectorAll('.copy-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const el = document.getElementById(btn.dataset.target);
      if (!el) return;
      const text = Array.from(el.querySelectorAll('.terminal__cmd'))
        .map(l => l.textContent.trim()).filter(Boolean).join('\n');
      navigator.clipboard.writeText(text);
      const orig = btn.textContent;
      btn.textContent = 'Copied!';
      setTimeout(() => btn.textContent = orig, 1500);
    });
  });
});
